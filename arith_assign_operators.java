public class arith_assign_operators{
    public static void main(String[] args){

        /*
        Arithmetric Assignment operators
        +=       a+=10        a=a+10
        -=       a-=10        a=a-10
        *=       a*=10        a=a*10
        /=       a/=10        a=a/10
        %=       a%=10        a=a%10
        
        */

        int a=129;
        System.out.println(a);      //129
        a+=10;
        System.out.println(a);      //139
        a-=10;
        System.out.println(a);      //129

        a%=10;
        System.out.println(a);


    }
}